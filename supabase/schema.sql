create table if not exists public.rentals (
  id bigint generated by default as identity primary key,
  item_name text not null check (btrim(item_name) <> ''),
  borrower text not null check (btrim(borrower) <> ''),
  rented_on date not null default current_date,
  returned_on date,
  created_at timestamptz not null default now(),
  constraint rentals_returned_on_after_rented_on
    check (returned_on is null or returned_on >= rented_on)
);

alter table public.rentals enable row level security;

drop policy if exists "Authenticated users can view rentals"
  on public.rentals;
create policy "Authenticated users can view rentals"
  on public.rentals
  for select
  to authenticated
  using (true);

drop policy if exists "Authenticated users can register rentals"
  on public.rentals;
create policy "Authenticated users can register rentals"
  on public.rentals
  for insert
  to authenticated
  with check (true);

drop policy if exists "Authenticated users can return rentals"
  on public.rentals;
create policy "Authenticated users can return rentals"
  on public.rentals
  for update
  to authenticated
  using (returned_on is null)
  with check (returned_on = current_date);

revoke all on public.rentals from anon, public;
grant select, insert on public.rentals to authenticated;
grant update (returned_on) on public.rentals to authenticated;
revoke all on sequence public.rentals_id_seq from anon, public;
grant usage, select on sequence public.rentals_id_seq to authenticated;
